    /**
     * Refreshes the course table with the latest course information
     * from the department's course catalog.
     * Clears the existing table rows and repopulates the table with
     * each course's number, name, credits, and price.
     */
    public final void refreshTable() {
        
        DefaultTableModel model = (DefaultTableModel) courseTable.getModel();
        model.setRowCount(0);

        Department department = business.getDepartment();
        CourseCatalog catalog = department.getCourseCatalog();
        for (Course course : catalog.getCourseList()) {
            Object[] row = new Object[5];
            row[0] = course;
            row[1] = course.getName();
            row[2] = course.getCredits();
            row[3] = course.getPrice();
            row[4] = course.getCoursePrice();
            model.addRow(row);
        }
        
    }
    
    private Course getSelectedCourse() {
        int selectedRow = courseTable.getSelectedRow();
        if (selectedRow < 0) {
            return null;
        }
        return (Course) courseTable.getValueAt(selectedRow, 0);
    }
