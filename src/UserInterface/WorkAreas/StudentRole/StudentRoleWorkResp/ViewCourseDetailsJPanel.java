    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        
        if (course == null) {
            // This should not happen
            return;
        }

        String number = txtCourseNumber.getText().trim();
        String name = txtCourseName.getText().trim();
        String creditsStr = txtCredits.getText().trim();
        String priceStr = txtPrice.getText().trim();

        // Fields validation
        if (number.isEmpty() || name.isEmpty() || creditsStr.isEmpty() || priceStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, 
                "All fields are required.", 
                "Validation Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        int credits;
        int price;
        try {
            credits = Integer.parseInt(creditsStr);
            if (credits <= 0) {
                JOptionPane.showMessageDialog(this,
                    "Credit hours must be greater than 0.",
                    "Validation Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                "Credit hours must be a valid whole number.",
                "Validation Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            price = Integer.parseInt(priceStr);
            if (price <= 0) {
                JOptionPane.showMessageDialog(this,
                    "Price per credit must be greater than 0.",
                    "Validation Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                "Price per credit must be a valid whole number.",
                "Validation Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Detect changes so an unnecessary update does not report a successful save
        boolean changed =
            !number.equals(course.getCourseNumber()) ||
            !name.equals(course.getName()) ||
            credits != course.getCredits() ||
            price != course.getPrice();

        if (!changed) {
            JOptionPane.showMessageDialog(
                this,
                "No changes were made to the course details.",
                "No Changes",
                JOptionPane.INFORMATION_MESSAGE
            );
            return;
        }

        // Update the shared Course object with the validated field values
        course.setCourseNumber(number);
        course.setName(name);
        course.setCredits(credits);
        course.setPrice(price);

        JOptionPane.showMessageDialog(
            this,
            "Course details updated successfully.",
            "Success",
            JOptionPane.INFORMATION_MESSAGE
        );

        // Refresh the course list so it displays the updated details
        refreshManageStudentCoursesJPanel();

        CardSequencePanel.remove(this);
        ((CardLayout) CardSequencePanel.getLayout()).next(CardSequencePanel);
    }//GEN-LAST:event_btnUpdateActionPerformed

