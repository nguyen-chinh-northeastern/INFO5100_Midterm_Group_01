    /**
     * Populates the form fields with the selected course's current details.
     */
    private void populateCourseDetails() {
        
        txtCourseNumber.setText(course.getCourseNumber());
        txtCourseName.setText(course.getName());
        txtCredits.setText(String.valueOf(course.getCredits()));
        txtPrice.setText(String.valueOf(course.getPrice()));
        txtTotalPrice.setText("$" + String.valueOf(course.getCoursePrice()));
        
    }
    
    /**
     * Refreshes the Manage Courses table after the course details change.
     */
    private void refreshManageStudentCoursesJPanel() {
        for (Component component : CardSequencePanel.getComponents()) {
            if (component instanceof RegistrationJPanel) {
                ((RegistrationJPanel) component).refreshTable();
                break;
            }
        }
    }
    
    /**
     * Recalculates and updates the total course price
     * whenever credits or price per credit are modified.
     */
    private void updateTotalPrice() {
        
        String creditsStr = txtCredits.getText().trim();
        String priceStr = txtPrice.getText().trim();

        try {
            if (!creditsStr.isEmpty() && !priceStr.isEmpty()) {
                int credits = Integer.parseInt(creditsStr);
                int price = Integer.parseInt(priceStr);

                if (credits > 0 && price >= 0) {
                    txtTotalPrice.setText("$" + (credits * price));
                    return;
                }
            }
        } catch (NumberFormatException e) {
            // The fallback will safely handle this
        }

        // Fallback if empty or invalid input
        txtTotalPrice.setText("---");
        
    }
