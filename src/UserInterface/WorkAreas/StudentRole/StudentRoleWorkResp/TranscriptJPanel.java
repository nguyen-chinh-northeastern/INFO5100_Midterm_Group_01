    // Calculate credits earned
    private int calculateTotalCreditsEarned(){
        int totalCredits = 0;
        if(studentProfile != null){
            ArrayList<SeatAssignment> courseList = studentProfile.getCourseList();
            if (courseList != null){
                for (SeatAssignment sa : courseList){
                    String semester = StudentUIUtils.getSemesterForSeatAssignment(studentProfile, sa);
                    if(!semester.equals("Unknown") && isPastYearSemester(semester)){
                        totalCredits += sa.getCreditHours();
                    }
              
            

            }
        }
       
        }
         return totalCredits;
    }
     

    
    
    private void displayStudentDetails(){
        if(studentProfile == null) return;
        
        // Populate student transcript fields
        if(studentProfile.getPerson() != null) {
            txtName.setText(studentProfile.getPerson().getPersonId());
            txtNuid.setText(studentProfile.getPerson().getNuid());
        }
        
        if(transcript != null){
            float gpa = calculateGPA(studentProfile);
            txtGPA.setText(String.format("%.2f", gpa));
            txtSatisfaction.setText(String.valueOf(transcript.getStudentSatifactionIndex()));
        }
        
        txtCreditsEarned.setText(String.valueOf(calculateTotalCreditsEarned()));
        txtDegree.setText("Master of Science in Information Systems (MSIS)"); //update to be dynamic

        }
  

    
    

    // Populate transcript table
    private void populateTranscriptTable(){
        DefaultTableModel model = (DefaultTableModel) tblTranscript.getModel();
        model.setRowCount(0);

        if(studentProfile == null) return;
       
        //Get student courses

        ArrayList<SeatAssignment> studentCourses = (studentProfile != null) ? studentProfile.getCourseList() : new ArrayList<>();
        if(studentCourses == null) return;
        
      
        for(SeatAssignment sa : studentCourses){
            if(sa.getAssociatedCourse() == null )continue;
            
            Object[] row = new Object[5];
            row[0] = sa.getAssociatedCourse().getCourseNumber();
            row[1] = sa.getAssociatedCourse().getName();
            row[2] = sa.getCreditHours();
            row[3] = sa.getLike() ? "Yes" : "No";
            row[4] = convertGpaToLetterGrade(sa);
            model.addRow(row);
    }
    }
    
   
    




