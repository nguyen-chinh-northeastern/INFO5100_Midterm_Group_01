    private void populateAssignmentsTable() {
        
        DefaultTableModel model = (DefaultTableModel) tblAssignments.getModel();
        model.setRowCount(0);
        
        if(selectedCourse == null) return;
        
        int totalExpected = StudentDataInitializer.getTotalAssignments(selectedCourse);
        for(int i = 1; i <= totalExpected; i++){
            String name = "Assignment " + i;
            Object[] row = new Object[3];
            row[0] = name;
            row[1] = "100 Pts";
            row[2] = getAssignmentStatus(selectedCourse, name);
            
            model.addRow(row);
        }
        //throw new UnsupportedOperationException("Not supported yet."); // Generated from nbfs://nbhost/SystemFileSystem/Templates/Classes/Code/GeneratedMethodBody
    }
    
    private void setViewMode(){
        txtSelectedCourse.setEditable(false);
        txtAssignmentStatus.setEditable(false);
        btnAttach.setEnabled(false);
        btnSubmit.setEnabled(false);
    }
    
    private void setEditMode(){
        btnAttach.setEnabled(true);
        btnRemove.setEnabled(attachedFile != null);
        btnSubmit.setEnabled(attachedFile != null);
    }
    
    private void backAction(){
        CardSequencePanel.removeAll();
        StudentWorkAreaJPanel studentDashboard = new StudentWorkAreaJPanel(business, studentProfile, CardSequencePanel);
        CardSequencePanel.add("student", studentDashboard);
        CardLayout layout = (CardLayout) CardSequencePanel.getLayout();
        layout.next(CardSequencePanel);
    }


