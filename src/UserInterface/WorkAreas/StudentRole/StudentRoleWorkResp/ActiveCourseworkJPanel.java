private void btnRemoveActionPerformed(java.awt.event.ActionEvent evt){
    attachedFile = null;
    lblFileIcon.setText("<No Document Attached>");
    btnSubmit.setEnabled(false);
    btnRemove.setEnabled(false);
}

private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt){
    if(attachedFile == null || selectedCourse == null) return;
    
    submitAssignment(selectedCourse, selectedAssignmentName);
    
    JOptionPane.showMessageDialog(this,
            "Assignment successfully submitted!",
            "Submission Success", JOptionPane.INFORMATION_MESSAGE);
    btnRemoveActionPerformed(null);
    
    populateAssignmentsTable();
    updateProgressBar();
    txtAssignmentStatus.setText(selectedAssignmentName + " - Submitted Successfully!");
}

private void backButtonActionPerformed(java.awt.event.ActionEvent evt){
    backAction();
}

    private void updateProgressBar() {
        if (selectedCourse == null) return;
        int max = StudentDataInitializer.getTotalAssignments(selectedCourse);
        int done = StudentDataInitializer.getSubmittedCount(selectedCourse);
        jProgressBar1.setMaximum(max);
        jProgressBar1.setValue(done);
        jProgressBar1.setStringPainted(true);
        jProgressBar1.setString(getProgressString(selectedCourse));
        //throw new UnsupportedOperationException("Not supported yet."); // Generated from nbfs://nbhost/SystemFileSystem/Templates/Classes/Code/GeneratedMethodBody
    }
    


