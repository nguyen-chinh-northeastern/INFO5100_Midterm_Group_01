    // method to populate semester combo box
    private void populateSemesterComboBox(){
        LocalDate today = LocalDate.now();
        int currentYear = today.getYear();
        int currentMonth = today.getMonthValue();
        
        List<String> semesters = new ArrayList<>();
        
        // determine available semesters
        if(currentMonth == 1){
            semesters.add("Spring" + currentYear);
            semesters.add("Summer" + currentYear);
            semesters.add("Fall" + currentYear);
        } else if (currentMonth <= 5) {
            semesters.add("Summer" + currentYear);
            semesters.add("Fall" + currentYear);
            semesters.add("Spring" + (currentYear + 1));
        }  else if (currentMonth <= 9) {
            semesters.add("Fall" + currentYear);
            semesters.add("Spring" + (currentYear + 1));
            semesters.add("Summer" + (currentYear + 1));
        } else {
            semesters.add("Spring" + (currentYear + 1));
            semesters.add("Summer" + (currentYear + 1));
            semesters.add("Fall" + (currentYear + 1));
        }
        
        cmbSemester.setModel(new DefaultComboBoxModel<>(semesters.toArray(new String[0])));
        
    }

    public final void refreshTable() {
        
        DefaultTableModel model = (DefaultTableModel) courseTable.getModel();
        model.setRowCount(0);

        Department department = business.getDepartment();
        CourseCatalog catalog = department.getCourseCatalog();
        for (Course course : catalog.getCourseList()) {
            Object[] row = new Object[5];
            row[0] = course;
            row[1] = course.getName();
            row[2] = course.getCredits();
            row[3] = course.getPrice();
            row[4] = course.getCoursePrice();
            model.addRow(row);
        }
        
    }
