    /**
     * Loads and populates the course selection combo box with all course offerings 
     * assigned to the logged-in faculty member.
     */
    private void loadAssignedCourses() {
        
        assignedOfferings = findAssignedOfferings();
        cmbCourses.removeAllItems();

        for (CourseOffer co : assignedOfferings) {
            cmbCourses.addItem(co.getCourseNumber() + " - " +  co.getSubjectCourse().getName());
        }

        if (cmbCourses.getItemCount() > 0) {
            cmbCourses.setSelectedIndex(0);
            displayClassPerformance();
        }
        
    }
    
    /**
     * Locate all course offerings taught by this faculty member.
     */
    private ArrayList<CourseOffer> findAssignedOfferings() {
        
        ArrayList<CourseOffer> offerings = new ArrayList<>();

        if (facultyProfile == null || business == null || business.getDepartment() == null) {
            return offerings;
        }

        // Get course offerings from faculty assignments
        ArrayList<FacultyAssignment> faList = facultyProfile.getFacultyAssignments();
        if (faList != null) {
            for (FacultyAssignment fa : faList) {
                CourseOffer co = fa.getCourseOffer();
                if (co != null && !offerings.contains(co)) {
                    offerings.add(co);
                }
            }
        }

        return offerings;
        
    }
    
    /**
     * Computes and displays student grades and summary statistics
     * for the selected course.
     */
    private void displayClassPerformance() {
        
        int idx = cmbCourses.getSelectedIndex();
        if (idx < 0 || idx >= assignedOfferings.size()) {
            return;
        }

        CourseOffer selectedOffer = assignedOfferings.get(idx);
        
        // Clear the table model before populating new data
        DefaultTableModel model = (DefaultTableModel) tblGrades.getModel();
        model.setRowCount(0);
        
        // Find all students in this course
        ArrayList<StudentProfile> studentList = findStudentsInCourse(selectedOffer);

        // Calculate grades and statistics
        int passCount = 0;
        float totalScore = 0;
        float highest = 0;
        float lowest = Float.MAX_VALUE;

        for (StudentProfile sp : studentList) {
            SeatAssignment sa = sp.getTranscript().findSeatAssignment(selectedOffer);
            float grade = sa.getGrade();

            totalScore += grade;
            if (grade >= 2.0f) passCount++;
            if (grade > highest) highest = grade;
            if (grade < lowest) lowest = grade;

            // Add student row to table
            model.addRow(new Object[]{
                sp.getPerson().getPersonId(),
                sp.getPerson().getNuid(),
                String.format("%.2f", grade),
                getLetterGrade(grade),
                grade >= 2.0f ? "Passing" : "Needs Review"
            });
        }

        // Update summary statistics
        int total = studentList.size();
        lblTotalStudentsVal.setText(String.valueOf(total));
        
        if (total > 0) {
            float avg = totalScore / total;
            lblClassAvgVal.setText(String.format("%.2f / 4.00 (%s)", avg, getLetterGrade(avg)));
            lblPassRateVal.setText(String.format("%.1f%%", ((float) passCount / total) * 100));
            lblHighLowVal.setText(String.format("%.1f / %.1f", highest, lowest));
        } else {
            lblClassAvgVal.setText("N/A");
            lblPassRateVal.setText("N/A");
            lblHighLowVal.setText("N/A");
        }
        
    }
    
    /**
     * Finds all students enrolled in the selected course offering.
     */
    private ArrayList<StudentProfile> findStudentsInCourse(CourseOffer selectedOffer) {
        
        ArrayList<StudentProfile> enrolledStudents = new ArrayList<StudentProfile>();
        StudentDirectory sd = business.getStudentDirectory();

        if (sd != null && sd.getStudentList() != null) {
            for (StudentProfile sp : sd.getStudentList()) {
                if (sp == null) continue;
                Transcript transcript = sp.getTranscript();
                if (transcript != null && transcript.findSeatAssignment(selectedOffer) != null) {
                    enrolledStudents.add(sp);
                }
            }
        }
        return enrolledStudents;
        
    }
    
    /**
     * Converts a grade point average (GPA) to its 
     * corresponding letter grade equivalent.
     * 
     * @param gpa the grade point average
     * @return the letter grade representation
     */
    private static String getLetterGrade(float gpa) {
        if (gpa >= 3.85f) return "A";
        if (gpa >= 3.70f) return "A-";
        if (gpa >= 3.30f) return "B+";
        if (gpa >= 3.00f) return "B";
        if (gpa >= 2.70f) return "B-";
        if (gpa >= 2.00f) return "C";
        return "F";
    }
    
