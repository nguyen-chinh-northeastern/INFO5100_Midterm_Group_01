    /**
     * Displays the student's basic info and hobbies/interests.
     */
    private void displayStudentInformation() {
        
        if (profile == null) return;
        Person p = profile.getPerson();

        if (p != null) {
            lblStudentNameVal.setText(p.getPersonId());
            lblNuidVal.setText(p.getNuid());
        }

        txtHobbies.setText(profile.getHobbies());
        txtInterests.setText(profile.getInterests());
        
    }
    
    /**
     * Populates course table with course registration info and course GPA.
     */
    private void populateEnrolledCoursesTable() {
        
        DefaultTableModel model = (DefaultTableModel) tblEnrolledCourses.getModel();
        model.setRowCount(0);

        if (profile == null || profile.getCourseList() == null) {
            return;
        }

        ArrayList<SeatAssignment> enrollments = profile.getCourseList();

        for (SeatAssignment sa : enrollments) {
            if (sa != null) {
                Course course = sa.getAssociatedCourse();
                if (course == null) continue;
                
                float grade = sa.getGrade();
                model.addRow(new Object[]{
                    course.getCourseNumber(),
                    course.getName(),
                    String.valueOf(sa.getCreditHours()),
                    String.format("%.2f", grade),
                    getLetterGrade(grade)
                });
            }
        }
    }
    
    /**
     * Converts a grade point average (GPA) to its 
     * corresponding letter grade equivalent.
     * 
     * @param gpa the grade point average
     * @return the letter grade representation
     */
    private static String getLetterGrade(float gpa) {
        if (gpa >= 3.85f) return "A";
        if (gpa >= 3.70f) return "A-";
        if (gpa >= 3.30f) return "B+";
        if (gpa >= 3.00f) return "B";
        if (gpa >= 2.70f) return "B-";
        if (gpa >= 2.00f) return "C";
        return "F";
    }
