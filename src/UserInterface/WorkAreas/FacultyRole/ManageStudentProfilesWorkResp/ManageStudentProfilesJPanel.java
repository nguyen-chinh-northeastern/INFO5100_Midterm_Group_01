    /**
     * Populates student table with registered student profile information.
     */
    private void populateStudentTable() {
        
        DefaultTableModel model = (DefaultTableModel) tblStudents.getModel();
        model.setRowCount(0);

        StudentDirectory sd = business.getStudentDirectory();
        if (sd == null || sd.getStudentList() == null) {
            return;
        }

        for (StudentProfile student : sd.getStudentList()) {
            Person person = student.getPerson();
            if (person != null) {
                Object[] row = new Object[5];
                row[0] = student;
                row[1] = person.getNuid();
                row[2] = person.getEmail();
                row[3] = person.getPhone();
                model.addRow(row);
            }
        }
        
    }
