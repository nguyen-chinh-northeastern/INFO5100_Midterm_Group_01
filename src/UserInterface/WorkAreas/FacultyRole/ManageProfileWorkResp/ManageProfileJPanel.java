    /**
     * Populates the form fields with the selected faculty's current details.
     */
    private void displayFacultyDetails() {
        
        if (profile == null) {
            return;
        }
        
        Person person = profile.getPerson();
        if (person == null) {
            return;
        }

        txtId.setText(person.getPersonId());
        txtNuid.setText(person.getNuid());
        txtEmail.setText(person.getEmail());
        txtPhone.setText(person.getPhone());
        txtDepartment.setText(person.getDepartment());
        txtAcademicRank.setText(profile.getAcademicRank());
        txtOfficeLocation.setText(profile.getOfficeLocation());

    }
