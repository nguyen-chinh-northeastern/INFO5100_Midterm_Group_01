    /**
     * Fills the table with one row per faculty profile.
     */
    public void refreshTable() {
        int rc = tblFaculty.getRowCount();
        for (int i = rc - 1; i >= 0; i--) {
            ((DefaultTableModel) tblFaculty.getModel()).removeRow(i);
        }

        UserAccountDirectory uad = business.getUserAccountDirectory();
        for (FacultyProfile fp : business.getFacultyDirectory().getTeacherList()) {
            Person p = fp.getPerson();
            Object[] row = new Object[4];
            row[0] = fp;
            row[1] = p == null ? "" : p.getNuid();
            row[2] = p == null ? "" : p.getEmail();
            row[3] = p == null ? "" : p.getPhone();

            ((DefaultTableModel) tblFaculty.getModel()).addRow(row);
        }
    }

