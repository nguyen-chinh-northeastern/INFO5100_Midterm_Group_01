    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (profile == null) {
            // This should not happen
            return;
        }

        Person person = profile.getPerson();
        if (person == null) {
            // This should not happen
            return;
        }

        String id = txtId.getText().trim();
        String nuid = txtNuid.getText().trim();
        String email = txtEmail.getText().trim();
        String phone = txtPhone.getText().trim();
        String department = txtDepartment.getText().trim();

        if (id.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "ID is required.",
                    "Validation Error",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }
        
        // Adding null check against department
        if(department.isEmpty()){
            JOptionPane.showMessageDialog(
                this,
                    "Department is required.",
                    "Validation Error",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (!nuid.matches("\\d{9}")) {
            JOptionPane.showMessageDialog(
                    this,
                    "NUID must be exactly 9 digits.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        // A non-empty NUID must be unique across all person records
        if (!nuid.isEmpty()) {
            Person existingPerson = business.getPersonDirectory().findPersonByNuid(nuid);

            if (existingPerson != null && existingPerson != person) {
                JOptionPane.showMessageDialog(
                        this,
                        "This NUID is already assigned to another person.",
                        "Validation Error",
                        JOptionPane.WARNING_MESSAGE
                );
                return;
            }
        }

        if (!email.matches("[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}")) {
            JOptionPane.showMessageDialog(
                    this,
                    "Email must be a valid address.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (!phone.matches("\\d{3}-\\d{3}-\\d{4}")) {
            JOptionPane.showMessageDialog(
                    this,
                    "Phone must be in the format ###-###-####.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        int hours;
        try {
            hours = Integer.parseInt(txtHours.getText().trim());
        } catch (NumberFormatException e) {
            hours = -1;
        }
        if (hours < 0 || hours > 168) {
            JOptionPane.showMessageDialog(
                    this,
                    "Hours must be a whole number in the range [0, 168].",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }
        boolean telework = chkTelework.isSelected();

        // Detect changes so an unnecessary update does not report a successful save
        boolean changed
                = !id.equals(person.getPersonId())
                || !nuid.equals(person.getNuid())
                || !email.equals(person.getEmail() == null ? "" : person.getEmail())
                || !phone.equals(person.getPhone() == null ? "" : person.getPhone())
                || !department.equals(person.getDepartment() == null ? "" : person.getDepartment())
                || hours != profile.getWorkingHoursPerWeek()
                || telework != profile.isTelework();

        if (!changed) {
            JOptionPane.showMessageDialog(
                    this,
                    "No changes were made to the admin profile.",
                    "No Changes",
                    JOptionPane.INFORMATION_MESSAGE
            );
            return;
        }

        // Update the Profile and Person object with the validated field values
        person.setPersonId(id);
        person.setNuid(nuid);
        person.setEmail(email);
        person.setPhone(phone);
        person.setDepartment(department);
        profile.setWorkingHoursPerWeek(hours);
        profile.setTelework(telework);

        // Locate if a UserAccount is bound to this person and trigger audit log
        for (UserAccount ua : business.getUserAccountDirectory().getUserAccountList()) {
            if (ua.getAssociatedPersonProfile() != null
                    && ua.getAssociatedPersonProfile().getPerson() == person) {
                ua.recordUpdate();
                break;
            }
        }

        JOptionPane.showMessageDialog(
                this,
                "Admin profile updated successfully.",
                "Success",
                JOptionPane.INFORMATION_MESSAGE
        );

        CardSequencePanel.remove(this);
        ((CardLayout) CardSequencePanel.getLayout()).next(CardSequencePanel);
    }//GEN-LAST:event_btnUpdateActionPerformed


