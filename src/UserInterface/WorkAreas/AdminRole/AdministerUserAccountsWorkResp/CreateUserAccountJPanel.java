    /**
     * Fill the profile combo box with profiles that have no account.
     */
    private void populateProfiles() {
        cmbProfile.removeAllItems();
        UserAccountDirectory uad = business.getUserAccountDirectory();
        for (Profile p : business.getStudentDirectory().getStudentList()) {
            if (uad.findByProfile(p) == null) {
                cmbProfile.addItem(p);
            }
        }
        for (Profile p : business.getFacultyDirectory().getTeacherList()) {
            if (uad.findByProfile(p) == null) {
                cmbProfile.addItem(p);
            }
        }
        for (Profile p : business.getEmployeeDirectory().getEmployeeList()) {
            if (uad.findByProfile(p) == null) {
                cmbProfile.addItem(p);
            }
        }
        if (cmbProfile.getItemCount() == 0) {
            JOptionPane.showMessageDialog(this,
                    "There are no profiles without user accounts. Add personnel in HR first.",
                    "Warning", JOptionPane.WARNING_MESSAGE);
            btnCreate.setEnabled(false);
            txtRole.setText("");
        } else {
            btnCreate.setEnabled(true);
        }
    }

